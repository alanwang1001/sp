#include <stdio.h>
#include <stdlib.h>
#include <unistd.h>
#include <sys/wait.h>

int main() {
    printf("【父行程】準備執行 ls -l 指令...\n");

    pid_t pid = fork(); // 步驟 1: 建立分身

    if (pid < 0) {
        perror("Fork 失敗");
        exit(1);
    } 
    else if (pid == 0) {
        // ---------------------------------------------------
        // 這裡是子行程 (分身) 的專屬區域
        // ---------------------------------------------------
        printf("【子行程】我是分身，我準備要犧牲自己，變成 ls 程式了！\n");

        // 準備 execvp 參數：
        // 參數 1: 要執行的指令名稱
        // 參數 2: 字串陣列，包含指令名稱本身，以及後續的參數，最後「必須」以 NULL 結尾！
        char *args[] = {"ls", "-l", NULL}; 

        // 步驟 2: 執行換腦手術
        // 'p' 代表它會去系統的 PATH 環境變數裡找 "ls" 在哪裡
        // 'v' 代表它吃的是一個陣列 (vector) args
        execvp(args[0], args);

        // --- 只有在 execvp 失敗時，程式才會走到這裡 ---
        // 如果上面的 execvp 成功找到並執行了 ls，下面這兩行「永遠不會」被印出來！
        perror("execvp 失敗了！找不到指令！");
        exit(1); 
    } 
    else {
        // ---------------------------------------------------
        // 這裡是父行程 (本尊) 的專屬區域
        // ---------------------------------------------------
        
        // 步驟 3: 父行程等待子行程執行完畢
        int status;
        waitpid(pid, &status, 0); 
        
        printf("【父行程】子行程 (ls) 已經執行結束，本尊要收工了。\n");
    }

    return 0;
}
